// 單字簡轉繁快查表
const CHAR_MAP = {};
Object.entries(SIMP_TO_TRAD_MAP).forEach(([k, v]) => {
  if ([...k].length === 1 && [...v].length === 1) {
    CHAR_MAP[k] = v;
  }
});

/**
 * 將搜尋字串標準化：
 * 1. 轉小寫
 * 2. NFD 去除拼音聲調符號（Hé Gǔ -> he gu）
 * 3. 常用中醫簡體轉繁體（风池 -> 風池、涌泉 -> 湧泉、内关 -> 內關）
 */
export function normalizeSearchText(raw) {
  if (!raw) return '';
  const stripped = String(raw)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();

  let out = '';
  for (const ch of stripped) {
    out += CHAR_MAP[ch] || ch;
  }
  return out.trim();
}

/**
 * 判斷 haystack（可為陣列或字串）是否命中查詢詞（同時相容帶空白與去空白拼音，如 "hegu" 命中 "Hé Gǔ"）
 */
export function matchesNormalizedQuery(haystackParts, rawQuery) {
  const qNorm = normalizeSearchText(rawQuery);
  if (!qNorm) return true;
  const qCompact = qNorm.replace(/\s+/g, '');

  const combined = Array.isArray(haystackParts) ? haystackParts.join(' ') : String(haystackParts || '');
  const hayNorm = normalizeSearchText(combined);
  if (hayNorm.includes(qNorm)) return true;

  if (qCompact.length >= 2) {
    const hayCompact = hayNorm.replace(/\s+/g, '');
    if (hayCompact.includes(qCompact)) return true;
  }
  return false;
}
